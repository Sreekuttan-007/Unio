from enum import StrEnum

from app.core.state import StateMachine


class IncidentStatus(StrEnum):
    SUBMITTED = "SUBMITTED"
    UNDER_REVIEW = "UNDER_REVIEW"
    NEEDS_CLARIFICATION = "NEEDS_CLARIFICATION"
    ACKNOWLEDGED = "ACKNOWLEDGED"
    ASSIGNED = "ASSIGNED"
    IN_PROGRESS = "IN_PROGRESS"
    RESOLVED = "RESOLVED"
    CLOSED = "CLOSED"


class IncidentEvent(StrEnum):
    REVIEW = "REVIEW"
    ACKNOWLEDGE = "ACKNOWLEDGE"
    REQUEST_CLARIFICATION = "REQUEST_CLARIFICATION"
    CLARIFY = "CLARIFY"
    ASSIGN = "ASSIGN"
    START = "START"
    RESOLVE = "RESOLVE"
    CLOSE = "CLOSE"
    REOPEN = "REOPEN"


S, E = IncidentStatus, IncidentEvent

INCIDENT_MACHINE: StateMachine[IncidentStatus, IncidentEvent] = StateMachine.build(
    [
        (S.SUBMITTED, E.REVIEW, S.UNDER_REVIEW),
        (S.SUBMITTED, E.ACKNOWLEDGE, S.ACKNOWLEDGED),
        (S.UNDER_REVIEW, E.ACKNOWLEDGE, S.ACKNOWLEDGED),
        (S.SUBMITTED, E.REQUEST_CLARIFICATION, S.NEEDS_CLARIFICATION),
        (S.UNDER_REVIEW, E.REQUEST_CLARIFICATION, S.NEEDS_CLARIFICATION),
        (S.ACKNOWLEDGED, E.REQUEST_CLARIFICATION, S.NEEDS_CLARIFICATION),
        (S.NEEDS_CLARIFICATION, E.CLARIFY, S.ACKNOWLEDGED),
        (S.ACKNOWLEDGED, E.ASSIGN, S.ASSIGNED),
        (S.ASSIGNED, E.START, S.IN_PROGRESS),
        (S.ACKNOWLEDGED, E.START, S.IN_PROGRESS),
        (S.ACKNOWLEDGED, E.RESOLVE, S.RESOLVED),
        (S.ASSIGNED, E.RESOLVE, S.RESOLVED),
        (S.IN_PROGRESS, E.RESOLVE, S.RESOLVED),
        (S.RESOLVED, E.CLOSE, S.CLOSED),
        (S.RESOLVED, E.REOPEN, S.ACKNOWLEDGED),
        (S.CLOSED, E.REOPEN, S.ACKNOWLEDGED),
    ]
)

OPEN_STATUSES = (S.SUBMITTED, S.UNDER_REVIEW, S.NEEDS_CLARIFICATION, S.ACKNOWLEDGED, S.ASSIGNED, S.IN_PROGRESS)
CLOSED_STATUSES = (S.RESOLVED, S.CLOSED)
