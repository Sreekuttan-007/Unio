from typing import Any


async def ensure_indexes(db: Any) -> None:
    """Idempotent. The unique indexes here are what make concurrent writes safe (docs/DATA_MODEL.md)."""
    await db["users"].create_index("email", unique=True)
    await db["audit_logs"].create_index([("entityType", 1), ("entityId", 1), ("at", -1)])
    await db["audit_logs"].create_index([("actorId", 1), ("at", -1)])
    await db["audit_logs"].create_index([("domain", 1), ("at", -1)])
    await db["idempotency_keys"].create_index("createdAt", expireAfterSeconds=24 * 3600)
    await db["revoked_tokens"].create_index("expiresAt", expireAfterSeconds=0)
    await db["outbox_events"].create_index([("dispatchedAt", 1), ("failedAt", 1), ("nextAttemptAt", 1)])
    await db["inbound_emails"].create_index("messageId", unique=True)
    await db["incidents"].create_index([("category", 1), ("buildingId", 1), ("status", 1)])
    await db["incidents"].create_index([("reporterIds", 1), ("updatedAt", -1)])
    await db["reports"].create_index([("incidentId", 1), ("createdAt", 1)])
    await db["reports"].create_index([("reporterId", 1), ("createdAt", -1)])
    await db["sla_instances"].create_index("subjectId", unique=True)
    await db["sla_policies"].create_index([("category", 1), ("priority", 1)], unique=True)
    await db["collision_checks"].create_index([("createdAt", -1)])
    await db["bookings"].create_index([("roomId", 1), ("startAt", 1)])
    await db["work_orders"].create_index([("assignedTechnicianId", 1), ("status", 1)])
    await db["work_orders"].create_index([("departmentId", 1), ("status", 1)])
    await db["work_orders"].create_index([("status", 1), ("priority", 1)])
    await db["work_orders"].create_index([("incidentId", 1), ("status", 1)])
    await db["work_order_events"].create_index([("workOrderId", 1), ("at", 1)])
    await db["technicians"].create_index("userId", unique=True)
    await db["shifts"].create_index([("technicianId", 1), ("startAt", 1)])
    await db["maintenance_history"].create_index([("technicianId", 1), ("completedAt", -1)])
    await db["timetable_sessions"].create_index([("roomId", 1), ("startAt", 1)])
    await db["stock_ledger"].create_index("postingKey", unique=True)
    await db["stock_ledger"].create_index("applied")
    await db["inventory_balances"].create_index("itemId")
    await db["reservations"].create_index([("workOrderId", 1), ("itemId", 1), ("status", 1)])
    await db["approvals"].create_index([("status", 1), ("createdAt", -1)])
    await db["approvals"].create_index([("requesterId", 1), ("createdAt", -1)])
    await db["goods_receipts"].create_index([("purchaseOrderId", 1)])
